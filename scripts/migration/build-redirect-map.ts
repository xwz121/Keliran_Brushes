// From a migration bundle, produce:
// - reports/brushes-redirect-map.csv: every keliran.com URL that moves here, in eight languages;
// - --main-repo=<path>: <path>/src/lib/brushes-redirects.ts, the slugs keliran.com redirects;
// - --write-shared-canonical: src/lib/shared-canonical.ts for shared documents copied verbatim.
// Usage: pnpm migration:redirects [--bundle=...] [--main-repo=../../Keliran.com/Keliran_Sealing]
import assert from 'node:assert/strict'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { contextKinds } from '../../src/lib/content-context'
import { locales } from '../../src/lib/locales'
import { routeFor } from '../../src/lib/routes'
import { arg, csv, flag, latestBundleDir, sourceSite, targetSite, type Bundle } from './lib'

const bundleDir = arg('bundle') || latestBundleDir()
const bundle: Bundle = JSON.parse(await readFile(path.join(bundleDir, 'bundle.json'), 'utf8'))
const moved = bundle.records.filter((r) => r.line === 'brushes')
assert.ok(moved.length, 'The bundle has no strip-brush documents')
const exported = bundle.exportedAt.slice(0, 10)

const rows: (string | null)[][] = [['locale', 'kind', 'collection', 'slug', 'old_url', 'new_url']]
for (const locale of locales) {
  rows.push([
    locale,
    'hub',
    'categories',
    '',
    `${sourceSite}/${locale}/strip-brushes`,
    `${targetSite}/${locale}/strip-brushes`,
  ])
  for (const r of moved) {
    const route = routeFor(r.collection, { slug: r.slug, line: r.line }, locale)
    rows.push([locale, 'detail', r.collection, r.slug, `${sourceSite}${route}`, `${targetSite}${route}`])
  }
  for (const query of [
    'line=brushes',
    ...moved.filter((r) => r.collection === 'products').map((r) => `product=${r.slug}`),
  ])
    rows.push([
      locale,
      'enquiry',
      'rfq',
      '',
      `${sourceSite}/${locale}/rfq?${query}`,
      `${targetSite}/${locale}/rfq?${query}`,
    ])
  for (const r of moved.filter((r) => (contextKinds as readonly string[]).includes(r.collection))) {
    const query = new URLSearchParams({ context: `${r.collection}/${r.slug}` }).toString()
    rows.push([
      locale,
      'enquiry',
      'rfq',
      r.slug,
      `${sourceSite}/${locale}/rfq?${query}`,
      `${targetSite}/${locale}/rfq?${query}`,
    ])
  }
  rows.push([
    locale,
    'catalogue',
    'products',
    '',
    `${sourceSite}/${locale}/products?line=brushes`,
    `${targetSite}/${locale}/products?line=brushes`,
  ])
}
await writeFile('reports/brushes-redirect-map.csv', csv(rows))

const bySlug = (collection: string) =>
  moved
    .filter((r) => r.collection === collection)
    .map((r) => r.slug)
    .sort()
const collections = [
  'products',
  'categories',
  'materials',
  'applications',
  'solutions',
  'cases',
  'guides',
  'faqs',
]
const mainRepo = arg('main-repo')
if (mainRepo) {
  const body = collections.map((c) => `  ${c}: ${JSON.stringify(bySlug(c))},`).join('\n')
  await writeFile(
    path.join(mainRepo, 'src/lib/brushes-redirects.ts'),
    `// Strip-brush documents moved to brushes.keliran.com with the same paths there.
// Generated by Keliran_Brushes scripts/migration/build-redirect-map.ts from the ${exported} export.
// Regenerate at cutover from the final export; keep these redirects for at least a year.
export const brushesSiteURL = (
  process.env.BRUSHES_SITE_URL || 'https://brushes.keliran.com'
).replace(/\\/$/, '')
export const movedToBrushes: Record<string, readonly string[]> = {
${body}
}
`,
  )
}
if (flag('write-shared-canonical')) {
  const paths = bundle.records
    .filter((r) => r.line === 'both' && r.collection !== 'pages')
    .map((r) => routeFor(r.collection, { slug: r.slug, line: r.line }, 'en').slice('/en'.length))
    .sort()
  await writeFile(
    'src/lib/shared-canonical.ts',
    `// Shared documents copied word for word from keliran.com during the split. Until each one is
// rewritten for this site, its canonical and hreflang point to the keliran.com original and it
// stays out of this site's sitemap, so search engines see one source for duplicated text.
// Remove a path once the rewritten version is published here.
// Generated by scripts/migration/build-redirect-map.ts from the ${exported} export.
export const sharedCanonicalPaths: ReadonlySet<string> = new Set<string>(${JSON.stringify(paths, null, 2)})
`,
  )
}
console.log(
  JSON.stringify({
    bundle: bundleDir,
    moved: Object.fromEntries(collections.map((c) => [c, bySlug(c).length])),
    redirectRows: rows.length - 1,
    mainRepo: mainRepo || null,
    sharedCanonical: flag('write-shared-canonical'),
  }),
)
